"""
quantize.py — convert the float model to integers, verify, and export for hardware.

Steps:
  1. Pick scale factors: inputs, W1, hidden activations (calibrated on training data), W2.
  2. Quantize weights to int8 and biases to int32 (in accumulator scale).
  3. Turn the layer-1 rescale factor into an integer multiply + shift (M0, shift).
  4. Run golden.py on the test set; compare accuracy to the float model.
  5. Measure how many bits each accumulator actually needs.
  6. Export: weight .mem files + params header for the RTL, test vectors for testbenches.

Run from the repo root:  python ml/quantize.py
"""

import os
import json

import numpy as np

from forward import CLASSES, N_IN, N_HIDDEN, N_OUT, forward_batch, relu
from golden import golden_forward

SPLIT_PATH = "data/split.npz"
FLOAT_WEIGHTS = "ml/weights/float_weights.npz"
QUANT_OUT = "ml/weights"
MEM_DIR = "rtl/mem"
VEC_DIR = "vectors"

CALIB_IMAGES = 10_000   # training images used to find the hidden-activation range
N_VECTORS = 100         # test images exported for the testbenches
M0_BITS = 16            # requant multiplier fits in a signed 16-bit value (< 2^15)
SEED = 0


# ---------------- quantization helpers ----------------
def quantize_symmetric(a, bits=8):
    """
    Map floats to signed ints in [-qmax, qmax] with ONE scale for the whole tensor:
        a ≈ a_q * scale
    Symmetric (no zero offset) keeps hardware simple: zero is exactly 0.
    We use -127..127 rather than -128..127 so the range is balanced.
    """
    qmax = 2 ** (bits - 1) - 1
    scale = np.abs(a).max() / qmax
    a_q = np.clip(np.round(a / scale), -qmax, qmax).astype(np.int64)
    return a_q, scale


def integer_multiplier(M, bits=M0_BITS):
    """
    Approximate a real number M (0 < M < 1) as M0 / 2^shift with M0 < 2^(bits-1).
    Bigger shift = more precision, so use the largest shift that keeps M0 in range.
    """
    limit = 2 ** (bits - 1) - 1
    shift = int(np.floor(np.log2(limit / M)))
    M0 = int(round(M * 2 ** shift))
    if M0 > limit:          # rounding can push it one over
        shift -= 1
        M0 = int(round(M * 2 ** shift))
    return M0, shift


def signed_bits(lo, hi):
    """Bits needed for a two's-complement register holding every value in [lo, hi]."""
    m = max(abs(int(lo)), abs(int(hi)) + 1)
    return int(np.ceil(np.log2(m))) + 1


# ---------------- export helpers ----------------
def write_mem(path, values, bits):
    """One hex value per line, two's complement, for Verilog $readmemh."""
    mask = (1 << bits) - 1
    digits = (bits + 3) // 4
    with open(path, "w") as f:
        for v in np.asarray(values).reshape(-1):
            f.write(f"{int(v) & mask:0{digits}x}\n")


def write_params_header(path, p):
    with open(path, "w") as f:
        f.write("// Auto-generated by ml/quantize.py — do not edit by hand.\n")
        f.write(f"localparam N_IN        = {N_IN};\n")
        f.write(f"localparam N_HIDDEN    = {N_HIDDEN};\n")
        f.write(f"localparam N_OUT       = {N_OUT};\n")
        f.write(f"localparam REQ_M0      = {p['M0']};\n")
        f.write(f"localparam REQ_SHIFT   = {p['shift']};\n")
        f.write(f"localparam ACC1_BITS   = {p['acc1_bits_worst']};  // worst case, layer 1\n")
        f.write(f"localparam ACC2_BITS   = {p['acc2_bits_worst']};  // worst case, layer 2\n")


# ---------------- main ----------------
if __name__ == "__main__":
    d = np.load(SPLIT_PATH)
    X_train, X_test, y_test = d["X_train"], d["X_test"], d["y_test"]
    w = np.load(FLOAT_WEIGHTS)
    W1, b1, W2, b2 = w["W1"], w["b1"], w["W2"], w["b2"]

    # 1. Scales -------------------------------------------------------------
    # Input: the model was trained on pixel/255, and the hardware receives raw 0..255,
    # so the input scale is exactly 1/255 and the FPGA needs no preprocessing.
    s_x = 1 / 255

    W1_q, s_w1 = quantize_symmetric(W1)
    W2_q, s_w2 = quantize_symmetric(W2)

    # Hidden activations: run the float model on training images and take the max
    # post-ReLU value, so 255 maps to the largest activation ever seen (no clipping).
    H_cal = relu(X_train[:CALIB_IMAGES].astype(np.float32) / 255 @ W1.T + b1)
    s_h = H_cal.max() / 255

    # 2. Biases in accumulator scale ---------------------------------------
    # acc1 = sum(W1_q * x_q) represents a real value of acc1 * (s_w1 * s_x),
    # so the bias must be expressed in that same unit before it's preloaded.
    b1_q = np.round(b1 / (s_w1 * s_x)).astype(np.int64)
    b2_q = np.round(b2 / (s_w2 * s_h)).astype(np.int64)

    # 3. Requantization multiplier -----------------------------------------
    # Converting acc1 (unit s_w1*s_x) to h_q (unit s_h) means multiplying by M:
    M = s_w1 * s_x / s_h
    M0, shift = integer_multiplier(M)
    M_err = abs(M0 / 2 ** shift - M) / M

    q = {"W1": W1_q, "b1": b1_q, "W2": W2_q, "b2": b2_q, "M0": M0, "shift": shift}

    print("scales:")
    print(f"  s_x  = {s_x:.6g}   (1/255)")
    print(f"  s_w1 = {s_w1:.6g}   s_w2 = {s_w2:.6g}   s_h = {s_h:.6g}")
    print(f"  requant M = {M:.6g}  ->  M0 = {M0}, shift = {shift}  "
          f"(M0/2^shift = {M0 / 2 ** shift:.6g}, rel. error {M_err:.2e})")

    # 4. Accuracy: float vs integer -----------------------------------------
    float_preds, _ = forward_batch(X_test.astype(np.float32) / 255, W1, b1, W2, b2)
    g = golden_forward(X_test, q)
    float_acc = (float_preds == y_test).mean()
    int_acc = (g["pred"] == y_test).mean()
    agree = (g["pred"] == float_preds).mean()

    print("\naccuracy on test set:")
    print(f"  float  {float_acc:.2%}")
    print(f"  int8   {int_acc:.2%}   (change {int_acc - float_acc:+.2%})")
    print(f"  int8 and float agree on {agree:.2%} of images")

    # 5. Bit widths ---------------------------------------------------------
    # Observed = what the test set actually produced. Worst case = any possible input.
    acc1_obs = signed_bits(g["acc1"].min(), g["acc1"].max())
    acc2_obs = signed_bits(g["acc2"].min(), g["acc2"].max())
    worst1 = N_IN * 255 * 127 + np.abs(b1_q).max()
    worst2 = N_HIDDEN * 255 * 127 + np.abs(b2_q).max()
    acc1_worst = signed_bits(-worst1, worst1)
    acc2_worst = signed_bits(-worst2, worst2)
    req_prod = int(np.maximum(g["acc1"], 0).max()) * M0

    print("\naccumulator widths (signed bits):")
    print(f"  layer 1: observed {acc1_obs}, worst case {acc1_worst}")
    print(f"  layer 2: observed {acc2_obs}, worst case {acc2_worst}")
    print(f"  requant product acc1*M0: observed max needs "
          f"{signed_bits(0, req_prod)} bits")

    hidden_sat = (g["h"] == 255).mean()
    print(f"  hidden activations clipped at 255: {hidden_sat:.3%} of values")

    # 6. Export -------------------------------------------------------------
    params = {
        "s_x": s_x, "s_w1": float(s_w1), "s_w2": float(s_w2), "s_h": float(s_h),
        "M": float(M), "M0": M0, "shift": shift,
        "float_acc": float(float_acc), "int_acc": float(int_acc),
        "acc1_bits_observed": acc1_obs, "acc1_bits_worst": acc1_worst,
        "acc2_bits_observed": acc2_obs, "acc2_bits_worst": acc2_worst,
    }
    os.makedirs(QUANT_OUT, exist_ok=True)
    np.savez(os.path.join(QUANT_OUT, "quant_weights.npz"), **q)
    with open(os.path.join(QUANT_OUT, "quant_params.json"), "w") as f:
        json.dump(params, f, indent=2)

    # Weight memories, row-major: address = neuron * fan_in + input_index
    os.makedirs(MEM_DIR, exist_ok=True)
    write_mem(os.path.join(MEM_DIR, "w1.mem"), W1_q, 8)    # 100,352 lines
    write_mem(os.path.join(MEM_DIR, "b1.mem"), b1_q, 32)   # 128 lines
    write_mem(os.path.join(MEM_DIR, "w2.mem"), W2_q, 8)    # 1,280 lines
    write_mem(os.path.join(MEM_DIR, "b2.mem"), b2_q, 32)   # 10 lines
    write_params_header(os.path.join(MEM_DIR, "quant_params.vh"), params)

    # Test vectors: random test images (the test set is sorted by class, so don't
    # just take the first N or they'd all be boomerangs)
    rng = np.random.default_rng(SEED)
    idx = np.sort(rng.choice(len(X_test), N_VECTORS, replace=False))
    gv = golden_forward(X_test[idx], q)
    os.makedirs(VEC_DIR, exist_ok=True)
    write_mem(os.path.join(VEC_DIR, "input.mem"), X_test[idx], 8)   # N x 784
    write_mem(os.path.join(VEC_DIR, "acc1.mem"), gv["acc1"], 32)    # N x 128, pre-ReLU
    write_mem(os.path.join(VEC_DIR, "hidden.mem"), gv["h"], 8)      # N x 128
    write_mem(os.path.join(VEC_DIR, "scores.mem"), gv["acc2"], 32)  # N x 10
    write_mem(os.path.join(VEC_DIR, "pred.mem"), gv["pred"], 4)     # N
    write_mem(os.path.join(VEC_DIR, "label.mem"), y_test[idx], 4)   # N

    print(f"\nexported weights + quant_params.vh to {MEM_DIR}/")
    print(f"exported {N_VECTORS} test vectors to {VEC_DIR}/ "
          f"(golden model correct on {(gv['pred'] == y_test[idx]).mean():.0%} of them)")